export const iso639FromCountryCode = (countryCode: CountryCode) => {
  return countryCodeMap[countryCode]?.iso639 || "";
};

const iso639ToLanguage = new Map(
  Object.values(countryCodeMap)
    .filter((entry) => entry.iso639)
    .map((entry) => [entry.iso639 as string, entry.language]),
);

export const languageNameFromIso639 = (iso639: string) => {
  return iso639ToLanguage.get(iso639) || "";
};
